	// navigation and chrome
	'solar:translation-2-bold-duotone',
	'solar:delivery-linear',
	'solar:link-linear',
	'solar:chart-2-linear',
	'solar:buildings-2-linear',
	'solar:settings-linear',
	'solar:logout-2-linear',
